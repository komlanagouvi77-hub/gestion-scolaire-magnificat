export function traduireTexte(texte) {
  const langue = typeof localStorage !== "undefined" ? localStorage.getItem("magnificat_langue") : "fr";
  if (langue !== "en") return texte;
  const espacesAvant = (texte.match(/^\s*/) || [""])[0];
  const espacesApres = (texte.match(/\s*$/) || [""])[0];
  const cle = texte.trim();
  let traduit = TRADUCTIONS_EN[cle];
  if (!traduit && cle.startsWith("Compte cree pour ")) traduit = "Account created for " + cle.slice("Compte cree pour ".length);
  if (!traduit && cle.startsWith("Presences enregistrees (")) traduit = "Attendance saved (" + cle.slice("Presences enregistrees (".length);
  if (!traduit && cle.startsWith("Votre demande a bien ete transmise")) traduit = "Your request has been sent to the administration. You will be notified after it has been reviewed. You can then sign in with the username and password you chose.";
  if (!traduit && cle.startsWith("Voici la situation de ")) traduit = "Here is the overview for " + cle.slice("Voici la situation de ".length).replace(/ aujourd'hui\.$/, " today.");
  if (!traduit && cle.startsWith("Pret pour votre journee a ")) traduit = "Ready for your day at " + cle.slice("Pret pour votre journee a ".length).replace(/ \?$/, "?");
  if (!traduit && cle.startsWith("Suivez la scolarite de vos enfants a ")) traduit = "Follow your children's education at " + cle.slice("Suivez la scolarite de vos enfants a ".length);
  if (!traduit && cle.startsWith("Chargement de ")) traduit = "Loading " + cle.slice("Chargement de ".length);
  if (!traduit && cle.startsWith("Espace ") && cle.endsWith(" selectionne")) traduit = cle.slice("Espace ".length, -" selectionne".length) + " portal selected";
  if (!traduit && cle.startsWith("Ce compte correspond a l'espace ")) {
    const details = cle.match(/^Ce compte correspond a l'espace (.+), pas (.+)\. Choisissez le bon espace ou laissez la selection vide\.$/);
    if (details) traduit = "This account is registered for the " + (TRADUCTIONS_EN[details[1]] || details[1]) + " portal, not " + (TRADUCTIONS_EN[details[2]] || details[2]) + ". Choose the correct portal or clear the selection.";
  }
  if (!traduit) {
    let correspondance = cle.match(/^(\d+) bulletin\(s\) genere\(s\)(?:, (\d+) eleve\(s\) sans notes saisies\.)?\.?$/);
    if (correspondance) traduit = correspondance[1] + " report card(s) generated" + (correspondance[2] ? ", " + correspondance[2] + " student(s) without grades entered." : ".");
    correspondance = cle.match(/^(\d+) note\(s\) enregistree\(s\)(?:, (\d+) en erreur\.)?\.?$/);
    if (!traduit && correspondance) traduit = correspondance[1] + " grade(s) saved" + (correspondance[2] ? ", " + correspondance[2] + " failed." : ".");
    correspondance = cle.match(/^Presences enregistrees \((\d+) changement\(s\)\)\.$/);
    if (!traduit && correspondance) traduit = "Attendance saved (" + correspondance[1] + " change(s)).";
    correspondance = cle.match(/^Supprimer l'evenement « (.+) » \?$/);
    if (!traduit && correspondance) traduit = "Delete the event \"" + correspondance[1] + "\"?";
    correspondance = cle.match(/^Supprimer la classe (.+) \?$/);
    if (!traduit && correspondance) traduit = "Delete class " + correspondance[1] + "?";
    correspondance = cle.match(/^Supprimer le compte de (.+) \?$/);
    if (!traduit && correspondance) traduit = "Delete the account for " + correspondance[1] + "?";
    correspondance = cle.match(/^Supprimer la matiere (.+) \?$/);
    if (!traduit && correspondance) traduit = "Delete subject " + correspondance[1] + "?";
    correspondance = cle.match(/^Supprimer ce paiement de (.+) FCFA pour (.+) \?$/);
    if (!traduit && correspondance) traduit = "Delete this payment of " + correspondance[1] + " FCFA for " + correspondance[2] + "?";
    correspondance = cle.match(/^Approuver cette demande et creer le compte de (.+) \?$/);
    if (!traduit && correspondance) traduit = "Approve this request and create an account for " + correspondance[1] + "?";
    correspondance = cle.match(/^Supprimer definitivement (.+) \((.+)\) \? Ses notes, absences, bulletins et paiements seront egalement supprimes\.$/);
    if (!traduit && correspondance) traduit = "Permanently delete " + correspondance[1] + " (" + correspondance[2] + ")? Their grades, absences, report cards, and payments will also be deleted.";
  }
  return espacesAvant + (traduit || cle) + espacesApres;
}

export function localeActive() {
  return typeof localStorage !== "undefined" && localStorage.getItem("magnificat_langue") === "en" ? "en-US" : "fr-FR";
}

